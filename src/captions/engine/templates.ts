export const groupOf = (id: string) => TEMPLATE_GROUPS.find((group) => GROUPS[group].includes(id));

/** Every font a template draws with. */
export const familiesOf = (style: Style) => {
  const families = [style.fontFamily, ...(style.rows?.rows.map((row) => row.fontFamily) ?? []), style.accent?.fontFamily];
  return [...new Set(families.filter((family) => family !== undefined))];
};
export const templateList = list;
